export function treeImage(index: number, season: TreeSeason, mature: boolean) {
  const frame = Math.max(0, Math.min(TREE_IMAGE_COUNT - 1, Math.floor(Number.isFinite(index) ? index : 0)));
  if (mature && frame >= MATURE_IMAGE) {
    if (season === 'fall') return AUTUMN[frame];
    if (season === 'winter') return WINTER[frame];
  }
  return TREE_IMAGES[frame];
}
